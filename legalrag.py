from sentence_transformers import CrossEncoder

# 1. Load a fast local Cross-Encoder model for reranking
print("Loading BAAI/bge-reranker-v2-m3 Cross-Encoder...")
reranker = CrossEncoder("BAAI/bge-reranker-v2-m3", max_length=512)

def retrieve_and_rerank(query, top_k_retrieval=10, top_k_rerank=3):
    print(f"\n--- Processing Query: '{query}' ---")

    # STAGE 1: Vector Search + Metadata Filtering (Retrieving candidate chunks)
    # ChromaDB similarity search gets candidate chunks
    initial_candidates = vectorstore.similarity_search(query, k=top_k_retrieval)
    print(f"Stage 1: Retrieved {len(initial_candidates)} candidate chunks via Vector Search.")

    # STAGE 2: Cross-Encoder Reranking
    # Prepare pairs for the Cross-Encoder: [[query, doc1_text], [query, doc2_text], ...]
    pairs = [[query, doc.page_content] for doc in initial_candidates]

    # Predict relevance scores (returns float scores for each candidate)
    scores = reranker.predict(pairs)

    # Attach scores to the documents and sort descending
    scored_docs = list(zip(initial_candidates, scores))
    scored_docs.sort(key=lambda x: x[1], reverse=True)

    # Select the top N reranked documents
    reranked_docs = [doc for doc, score in scored_docs[:top_k_rerank]]

    print(f"Stage 2: Reranked candidates and selected top {top_k_rerank} chunks.\n")

    # Display the top reranked chunks with scores
    for i, (doc, score) in enumerate(scored_docs[:top_k_rerank]):
        print(f"Rank {i+1} (Reranker Score: {score:.4f}):")
        print(f"  Chunk ID: {doc.metadata['chunk_id']}")
        print(f"  Parties: {doc.metadata['primary_parties']}")
        print(f"  Text: {doc.page_content[:180]}...\n")

    return reranked_docs

