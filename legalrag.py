from langchain_text_splitters import RecursiveCharacterTextSplitter
from langchain_core.documents import Document

# 1. Initialize the Text Splitter
# 800 characters per chunk with 150 character overlap keeps legal clauses intact
text_splitter = RecursiveCharacterTextSplitter(
    chunk_size=800,
    chunk_overlap=150,
    separators=["\n\n", "\n", " ", ""]
)

# 2. Split the raw document text into chunks
raw_chunks = text_splitter.split_text(raw_text)

# 3. Create Document Objects with Inherited Metadata
chunked_documents = []

for idx, chunk_str in enumerate(raw_chunks):
    # Copy global metadata so each chunk gets its own independent dictionary
    chunk_metadata = doc_metadata.copy()

    # Add chunk-specific tracking IDs
    chunk_metadata["chunk_id"] = f"{doc_metadata['source_file']}_chunk_{idx}"
    chunk_metadata["chunk_index"] = idx

    # Create LangChain Document object
    doc = Document(
        page_content=chunk_str,
        metadata=chunk_metadata
    )
    chunked_documents.append(doc)

