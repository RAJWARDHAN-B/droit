import re
import spacy

nlp = spacy.load("en_core_web_sm")

# Words that spaCy misidentifies as ORG/PERSON in legal text
LEGAL_NOISE_WORDS = {
    "party", "effective date", "definitions", "suite", "deliverab",
    "the service provider", "this master services agreement", "agreement",
    "section", "schedule", "exhibit", "innovation plaza"
}

def clean_parties(raw_entities):
    cleaned = []
    for ent in raw_entities:
        ent_clean = ent.strip()
        # Filter out short terms, legal noise words, and title-case section headers
        if (
            len(ent_clean) > 3
            and ent_clean.lower() not in LEGAL_NOISE_WORDS
            and not ent_clean.isupper()  # Filters out "DEFINITIONS"
        ):
            cleaned.append(ent_clean)

    # Deduplicate entries where one is a substring of another (e.g., keep "Atharva Pvt. Ltd." over "Atharva Pvt")
    final_parties = []
    for p in sorted(cleaned, key=len, reverse=True):
        if not any(p in existing for existing in final_parties):
            final_parties.append(p)

    return final_parties

def extract_refined_metadata(file_path):
    with open(file_path, "r", encoding="utf-8") as f:
        text = f.read()

    # 1. Extract Entities from the first 1200 characters (Document Header)
    header_text = text[:1200]
    doc = nlp(header_text)
    raw_entities = [ent.text.strip() for ent in doc.ents if ent.label_ in ["ORG", "PERSON"]]

    # Clean the extracted parties
    parties = clean_parties(raw_entities)

    # 2. Extract Document Type
    doc_type = "General Legal Document"
    if re.search(r"non-disclosure agreement|\bnda\b", text, re.IGNORECASE):
        doc_type = "NDA"
    elif re.search(r"master services agreement|\bmsa\b", text, re.IGNORECASE):
        doc_type = "MSA"
    elif re.search(r"employment agreement|employment contract", text, re.IGNORECASE):
        doc_type = "Employment Agreement"

    # 3. Extract Primary Effective Date
    effective_date_match = re.search(
        r"(?:effective|entered into|dated as of)\s+(?:on\s+)?(\b\d{4}-\d{2}-\d{2}\b|\b(?:January|February|March|April|May|June|July|August|September|October|November|December)\s+\d{1,2},\s+\d{4}\b)",
        text,
        re.IGNORECASE
    )

    all_dates = list(set(re.findall(
        r"(\b\d{4}-\d{2}-\d{2}\b|\b(?:January|February|March|April|May|June|July|August|September|October|November|December)\s+\d{1,2},\s+\d{4}\b)",
        text,
        re.IGNORECASE
    )))

    primary_date = effective_date_match.group(1) if effective_date_match else (all_dates[0] if all_dates else "Unknown")

    global_metadata = {
        "doc_type": doc_type,
        "primary_parties": parties,
        "effective_date": primary_date,
        "total_dates_found": len(all_dates),
        "source_file": file_path
    }

    return text, global_metadata

