import os
from groq import Groq

# 1. Set your Groq API key
# Get one for free at: https://console.groq.com/keys
os.environ["GROQ_API_KEY"] = ""


client = Groq(api_key=os.environ.get("GROQ_API_KEY"))

def generate_rag_answer_groq(query, top_chunks):
    # Format context from reranked chunks with their inherited metadata
    formatted_context = ""
    for i, doc in enumerate(top_chunks):
        formatted_context += f"--- CONTEXT SNIPPET {i+1} ---\n"
        formatted_context += f"Source File: {doc.metadata.get('source_file')}\n"
        formatted_context += f"Contract Type: {doc.metadata.get('doc_type')}\n"
        formatted_context += f"Primary Parties: {', '.join(doc.metadata.get('primary_parties', []))}\n"
        formatted_context += f"Effective Date: {doc.metadata.get('effective_date')}\n"
        formatted_context += f"Content:\n{doc.page_content}\n\n"

    system_instruction = (
        "You are a helpful legal assistant. Answer the user's question using ONLY the provided text snippets and metadata. "
        "If the answer is not explicitly mentioned in the context, state 'I cannot find this information in the provided document.' "
        "Do not hallucinate or assume facts not present in the context."
    )

    user_prompt = f"""DOCUMENT CONTEXT:
{formatted_context}

USER QUESTION:
{query}
"""

    # Query Groq API using Llama-3.3 70B
    chat_completion = client.chat.completions.create(
        messages=[
            {"role": "system", "content": system_instruction},
            {"role": "user", "content": user_prompt},
        ],
        model="llama-3.3-70b-versatile",
        temperature=0.1,  # Low temperature for factual, deterministic legal answers
    )

    return chat_completion.choices[0].message.content

